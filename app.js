async function drawProfileHistory(playerId) {
    const canvas=document.getElementById("profileHistoryChart"); if(!canvas) return;
    const ctx=canvas.getContext("2d"), w=canvas.width, h=canvas.height;
    ctx.clearRect(0,0,w,h);
    try {
        const history=(await getHistory()).filter(x=>String(x.playerId)===String(playerId)).sort((a,b)=>new Date(a.date.replace(" ","T"))-new Date(b.date.replace(" ","T"))).slice(-18);
        if(history.length<2){ctx.fillStyle="#777";ctx.font="12px Arial";ctx.fillText("Not enough history yet.",15,30);return;}
        const gains=history.map((x,i)=>i?Math.max(0,Number(x.kills)-Number(history[i-1].kills)):0);
        const max=Math.max(...gains,1), pad=22;
        ctx.strokeStyle="#292929"; ctx.lineWidth=1;
        for(let i=0;i<4;i++){let y=pad+(h-pad*2)*i/3;ctx.beginPath();ctx.moveTo(pad,y);ctx.lineTo(w-pad,y);ctx.stroke();}
        ctx.beginPath(); ctx.strokeStyle="#d4af37"; ctx.lineWidth=2;
        gains.forEach((v,i)=>{const x=pad+(w-pad*2)*i/(gains.length-1);const y=h-pad-(v/max)*(h-pad*2);if(i)ctx.lineTo(x,y);else ctx.moveTo(x,y);});ctx.stroke();
        ctx.fillStyle="#fff";ctx.font="10px Arial";ctx.fillText("Kills gained per recorded update",pad,12);
    } catch(e){console.error(e);}
}

