const LAST_UPDATED_URL =
    "https://raw.githubusercontent.com/corderox1/tanktrouble-leaderboard/main/last_updated.json";

let lastKnownUpdate = null;

async function checkForLeaderboardUpdate() {

    try {

        const response = await fetch(
            LAST_UPDATED_URL + "?time=" + Date.now()
        );

        const data = await response.json();

        if (!data.lastUpdated) {
            return;
        }

        const githubUpdateTime = data.lastUpdated;

        // First check: just remember the current GitHub update
        if (lastKnownUpdate === null) {

            lastKnownUpdate = githubUpdateTime;

            updateLastUpdatedDisplay(githubUpdateTime);

            return;
        }

        // GitHub has a newer leaderboard update
        if (githubUpdateTime !== lastKnownUpdate) {

            console.log("New leaderboard update detected!");

            lastKnownUpdate = githubUpdateTime;

            updateLastUpdatedDisplay(githubUpdateTime);

            // Reload all leaderboard data
            loadLeaderboard(currentType, currentStat);
            loadLifetimeLeaderboard("kills");
            loadLaika(currentType, currentStat);

        }

    } catch (error) {

        console.error(
            "Could not check leaderboard update time:",
            error
        );

    }

}


