function loadPlayerTank(player) {
    const canvas = document.getElementById("playerTankCanvas");
    if (!canvas) return;

    // Render internally at TankTrouble's 640px asset resolution.
    const width = 640;
    const height = 384;

    canvas.width = width;
    canvas.height = height;

    const ctx = canvas.getContext("2d");
    ctx.clearRect(0, 0, width, height);

    const baseUrl = "https://tanktrouble.com/";

    function loadImage(path) {
        return new Promise((resolve, reject) => {
            const img = new Image();
            img.onload = () => resolve(img);
            img.onerror = () => reject(new Error("Failed to load: " + path));
            img.src = baseUrl + path;
        });
    }

    function colourValue(colour) {
        if (!colour) return "#888888";

        if (colour.numericValue) {
            let value = colour.numericValue.substring(2).padStart(6, "0");
            return "#" + value;
        }

        return null;
    }

    async function resolveColour(colour) {
        if (colour && colour.imageValue) {
            const path = TANK_ASSETS["colours/colour" + colour.imageValue];

            if (path) {
                return await loadImage(path);
            }
        }

        return colourValue(colour);
    }

    function tintPart(bufferCtx, image, colour) {
        bufferCtx.clearRect(0, 0, width, height);

        bufferCtx.globalCompositeOperation = "copy";

        if (colour instanceof HTMLImageElement) {
            bufferCtx.drawImage(colour, 0, 0, width, height);
        } else {
            bufferCtx.fillStyle = colour || "#888888";
            bufferCtx.fillRect(0, 0, width, height);
        }

        bufferCtx.globalCompositeOperation = "destination-atop";
        bufferCtx.drawImage(image, 0, 0, width, height);
        bufferCtx.globalCompositeOperation = "source-over";
    }

    async function drawTank() {
        try {
            const [
                turret,
                barrel,
                leftTread,
                rightTread,
                base,
                turretShade,
                barrelShade,
                leftTreadShade,
                rightTreadShade,
                baseShade
            ] = await Promise.all([
                loadImage(TANK_ASSETS.turret),
                loadImage(TANK_ASSETS.barrel),
                loadImage(TANK_ASSETS.leftTread),
                loadImage(TANK_ASSETS.rightTread),
                loadImage(TANK_ASSETS.base),
                loadImage(TANK_ASSETS.turretShade),
                loadImage(TANK_ASSETS.barrelShade),
                loadImage(TANK_ASSETS.leftTreadShade),
                loadImage(TANK_ASSETS.rightTreadShade),
                loadImage(TANK_ASSETS.baseShade)
            ]);

            const [
                turretColour,
                treadColour,
                baseColour
            ] = await Promise.all([
                resolveColour(player.turretColour),
                resolveColour(player.treadColour),
                resolveColour(player.baseColour)
            ]);

            const accessoryImages = {};

            const accessoryList = [
                ["turret", player.turretAccessory],
                ["barrel", player.barrelAccessory],
                ["front", player.frontAccessory],
                ["back", player.backAccessory]
            ];

            await Promise.all(
                accessoryList.map(async ([type, id]) => {
                    if (
                        id === undefined ||
                        id === null ||
                        id === "" ||
                        id === "0" ||
                        id === 0
                    ) {
                        return;
                    }

                    const path =
                        TANK_ASSETS["accessories/" + type + id];

                    if (!path) {
                        console.warn(
                            "No TankTrouble asset found:",
                            type + id
                        );
                        return;
                    }

                    try {
                        accessoryImages[type] = await loadImage(path);
                    } catch (error) {
                        console.warn(
                            "Could not load accessory:",
                            type + id
                        );
                    }
                })
            );

            /*
             * This follows TankTrouble's actual drawTankIcon order:
             *
             * BACK
             * LEFT TREAD
             * TURRET
             * BASE
             * RIGHT TREAD
             * BARREL
             * TURRET ACCESSORY
             * FRONT ACCESSORY
             * BARREL ACCESSORY
             *
             * The old renderer drew the treads in a different order,
             * which caused the left tread to look corrupted.
             */

            const composited =
                document.createElement("canvas");

            composited.width = width;
            composited.height = height;

            const w = composited.getContext("2d");

            const tinted =
                document.createElement("canvas");

            tinted.width = width;
            tinted.height = height;

            const tintCtx = tinted.getContext("2d");

            // BACK ACCESSORY
            if (accessoryImages.back) {
                w.drawImage(
                    accessoryImages.back,
                    0, 0, width, height
                );
            }

            // LEFT TREAD
            tintPart(
                tintCtx,
                leftTread,
                treadColour
            );

            w.drawImage(tinted, 0, 0);
            w.drawImage(
                leftTreadShade,
                0, 0, width, height
            );

            // TURRET
            tintPart(
                tintCtx,
                turret,
                turretColour
            );

            w.drawImage(tinted, 0, 0);
            w.drawImage(
                turretShade,
                0, 0, width, height
            );

            // BASE
            tintPart(
                tintCtx,
                base,
                baseColour
            );

            w.drawImage(tinted, 0, 0);
            w.drawImage(
                baseShade,
                0, 0, width, height
            );

            // RIGHT TREAD
            tintPart(
                tintCtx,
                rightTread,
                treadColour
            );

            w.drawImage(tinted, 0, 0);
            w.drawImage(
                rightTreadShade,
                0, 0, width, height
            );

            // BARREL
            tintPart(
                tintCtx,
                barrel,
                turretColour
            );

            w.drawImage(tinted, 0, 0);
            w.drawImage(
                barrelShade,
                0, 0, width, height
            );

            // TURRET ACCESSORY
            if (accessoryImages.turret) {
                w.drawImage(
                    accessoryImages.turret,
                    0, 0, width, height
                );
            }

            // FRONT ACCESSORY
            if (accessoryImages.front) {
                w.drawImage(
                    accessoryImages.front,
                    0, 0, width, height
                );
            }

            // BARREL ACCESSORY
            if (accessoryImages.barrel) {
                w.drawImage(
                    accessoryImages.barrel,
                    0, 0, width, height
                );
            }

            /*
             * TankTrouble's outline pass.
             */
            const outline =
                document.createElement("canvas");

            outline.width = width;
            outline.height = height;

            const outlineCtx =
                outline.getContext("2d");

            outlineCtx.globalCompositeOperation = "copy";
            outlineCtx.fillStyle = "rgba(0,0,0,0.8)";
            outlineCtx.fillRect(
                0, 0, width, height
            );

            outlineCtx.globalCompositeOperation =
                "destination-atop";

            outlineCtx.drawImage(
                composited,
                0, 0
            );

            const outlineWidth = 1;
            const diagonal =
                Math.sqrt(
                    outlineWidth * outlineWidth / 2
                );

            ctx.clearRect(0, 0, width, height);

            ctx.drawImage(outline, -outlineWidth, 0);
            ctx.drawImage(outline, -diagonal, -diagonal);
            ctx.drawImage(outline, -diagonal, diagonal);
            ctx.drawImage(outline, 0, outlineWidth);
            ctx.drawImage(outline, 0, -outlineWidth);
            ctx.drawImage(outline, diagonal, -diagonal);
            ctx.drawImage(outline, diagonal, diagonal);
            ctx.drawImage(outline, outlineWidth, 0);

            ctx.drawImage(composited, 0, 0);

            ctx.globalCompositeOperation = "source-over";

        } catch (error) {
            console.error(
                "Could not render TankTrouble tank:",
                error
            );
        }
    }

    drawTank();
}

