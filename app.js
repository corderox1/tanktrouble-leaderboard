const DATA_BASE = "https://raw.githubusercontent.com/corderox1/tanktrouble-leaderboard/main/";
let statsCache = null;
let historyCache = null;
let leaderboardCache = {};

async function fetchJsonFile(name) {
    const response = await fetch(DATA_BASE + name + "?time=" + Date.now());
    if (!response.ok) throw new Error("Could not load " + name);
    return response.json();
}

async function getStats() {
    if (!statsCache) statsCache = await fetchJsonFile("stats.json");
    return statsCache;
}

async function getHistory() {
    if (!historyCache) historyCache = await fetchJsonFile("history.json");
    return historyCache;
}

async function getBoard(period, stat="kills") {
    const key = period + "_" + stat;
    if (!leaderboardCache[key]) {
        leaderboardCache[key] = await fetchJsonFile(
            stat === "wins" ? period + "_wins.json" : period + ".json"
        );
    }
    return leaderboardCache[key];
}

function realOnly(list) {
    return (list || []).filter(p => String(p.username).toLowerCase() !== "laika");
}

function playerRank(list, id) {
    const clean = realOnly(list);
    const index = clean.findIndex(p => String(p.playerId) === String(id));
    return index >= 0 ? index + 1 : null;
}

function rankText(rank) {
    return rank ? "#" + rank.toLocaleString() : "—";
}

function safeName(name) {
    return String(name).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;","\"":"&quot;","'":"&#39;"}[c]));
}

